def build_corpus(output):
    groups = {
        'neutral': (TASKS, ['我们先{item}，完成以后再继续吧。', '今天记得{item}，不要把这件事忘了。', '如果有时间，就先{item}，这样会轻松一点。', '现在可以{item}，我会陪着你慢慢做。', '先别着急，把{item}这件事安排好就行。', '我已经准备好了，我们一起{item}吧。', '等你休息好了，再{item}也来得及。', '你想先{item}，还是先放松一下呢？', '不妨先{item}，看看能不能找到新的思路。', '今天的小目标是{item}，一步一步来就好。']),
        'happy': (TASKS, ['太好了！你已经开始{item}了，今天的进展很不错呀！', '好耶！我们一起{item}，感觉今天一定会很顺利。', '听说你准备{item}，我也跟着期待起来了！', '嘿嘿，能和你一起{item}，真是一件开心的事情。', '今天不如{item}吧！说不定会有小小的惊喜哦。']),
        'gentle': (TASKS, ['不用太着急，等心情放松一点，再{item}也没关系。', '如果你愿意，我会陪你{item}，慢慢来就好。', '先照顾好自己，再{item}，我会一直在这里等你。']),
        'teasing': (FORGETFUL, ['哎呀，你该不会{item}了吧？我可是看见了哦。', '别装作没听见啦，是不是{item}了？快老实交代。', '让我猜猜，你是不是{item}了？这次可不能糊弄我。', '你又{item}了对不对？好啦，我会帮你记着的。', '嗯哼，要是你{item}，我可要认真提醒你了。']),
        'shy': (REQUESTS, ['那个，其实我想请你{item}，可以吗？', '如果不会打扰你，能不能{item}？我有一点期待。', '有句话一直想说，如果你愿意{item}，我会很开心。']),
        'surprised': (ACHIEVEMENTS, ['真的吗？你已经{item}了？这也太厉害了吧！', '咦，你居然{item}了！我还以为要花很久呢。', '等一下，你是说你已经{item}了？我没听错吧？', '哇，原来你已经{item}了！真是让我刮目相看。', '没想到这么快就能{item}！你今天状态真好呀。']),
        'angry': (BEHAVIORS, ['不可以再{item}了！答应过我的事情要记得做到。', '你怎么又{item}？这次我真的要认真提醒你了。', '我不是在开玩笑，不能再{item}，先照顾好自己！', '明明说好了不再{item}，你可不能偷偷反悔。']),
        'sad': (SETBACKS, ['如果你{item}，就先休息一下吧，我会陪着你。', '今天{item}也没关系，我们明天再慢慢尝试。', '听到你{item}，我也有一点难过，不过你不是一个人。']),
    }
    corpus = []
    for emotion, (items, templates) in groups.items():
        for template in templates:
            for item in items:
                text = template.format(item=item)
                corpus.append({'id': f'cn_{len(corpus) + 1:04d}', 'emotion': emotion, 'text': text})
    assert len(corpus) == 800
    assert len({record['text'] for record in corpus}) == 800
    assert all(6 <= len(record['text']) <= 60 for record in corpus)
    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(corpus, ensure_ascii=False, indent=2), encoding='utf-8')
    return corpus
